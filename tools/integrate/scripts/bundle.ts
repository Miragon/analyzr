/**
 * Bundles each script entry of `src/cli/` into one self-contained ES module
 * for `plugins/analyzr-integrate/scripts/` (a marketplace install has no
 * node_modules) with rolldown, the bundler Vite uses (one locked version in
 * the workspace), and renders the plugin's THIRD-PARTY-NOTICES.md from the
 * modules each bundle contains. Used by `generate.ts` (writes) and the drift
 * test (compares); the output depends only on the sources and the lockfile:
 * rolldown's `//#region <path>` comments are rewritten to `<package>@<version>/
 * <file>` (or `src/…` for this package), so neither the pnpm store layout nor
 * a home directory ends up in the bundles.
 */
import { existsSync, readFileSync } from 'node:fs';
import { readdir, readFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { rolldown } from 'rolldown';

export const PACKAGE_ROOT = fileURLToPath(new URL('../', import.meta.url));
export const REPO_ROOT = fileURLToPath(new URL('../../../', import.meta.url));

/** The plugin folder, relative to the repository root. */
export const PLUGIN_DIR = 'plugins/analyzr-integrate';

/** Bundled script (in `<plugin>/scripts/`) → entry source (below tools/integrate). */
export const ENTRIES: Readonly<Record<string, string>> = {
  'inspect.mjs': 'src/cli/inspect.ts',
  'normalize-bpmn.mjs': 'src/cli/normalize-bpmn.ts',
};

export const NOTICES_FILE = 'THIRD-PARTY-NOTICES.md';

/** A third-party package whose code a bundle contains. */
export interface BundledPackage {
  name: string;
  version: string;
  license: string;
  homepage: string | null;
  texts: { file: string; text: string }[];
  scripts: string[];
}

export interface BuildResult {
  /** Path relative to the repository root → content. */
  files: Map<string, string>;
  packages: BundledPackage[];
}

const compare = (a: string, b: string): number => (a < b ? -1 : a > b ? 1 : 0);

function banner(script: string, entry: string): string {
  return [
    '#!/usr/bin/env node',
    `// Generated by \`pnpm --filter @analyzr/integrate generate\` from tools/integrate/${entry}.`,
    '// Do not edit: change the sources and generate again (a test compares this file).',
    `// Bundles third-party code under its own licenses: see ../${NOTICES_FILE}.`,
    `// Run: node ${script} --help`,
  ].join('\n');
}

/** The package directory below the last `node_modules/` of a module path, or `null`. */
export function packageDirOf(moduleId: string): string | null {
  const marker = `${path.sep}node_modules${path.sep}`;
  const at = moduleId.lastIndexOf(marker);
  if (at < 0) return null;
  const rest = moduleId.slice(at + marker.length).split(path.sep);
  const segments = rest[0]?.startsWith('@') ? 2 : 1;
  return moduleId.slice(0, at + marker.length) + rest.slice(0, segments).join(path.sep);
}

/** `name@version` of the nearest package.json with a name above `file`, and its folder. */
function owningPackage(file: string): { id: string; dir: string } | null {
  for (let dir = path.dirname(file); ; dir = path.dirname(dir)) {
    const manifest = path.join(dir, 'package.json');
    if (existsSync(manifest)) {
      const pkg = JSON.parse(readFileSync(manifest, 'utf8')) as {
        name?: unknown;
        version?: unknown;
      };
      if (typeof pkg.name === 'string') {
        return { id: `${pkg.name}@${String(pkg.version)}`, dir };
      }
    }
    if (path.dirname(dir) === dir) return null;
  }
}

/**
 * A region comment's path (relative to this package, as rolldown writes it)
 * as `src/…` for this package's own modules and `<package>@<version>/<file>`
 * for every other one.
 */
export function regionName(region: string): string {
  if (/^\0|^rolldown:/.test(region)) return region;
  const absolute = path.resolve(PACKAGE_ROOT, region);
  const owner = owningPackage(absolute);
  if (owner === null) throw new Error(`no package.json above the bundled module ${region}`);
  const inside = path.relative(owner.dir, absolute).split(path.sep).join('/');
  return path.resolve(owner.dir) === path.resolve(PACKAGE_ROOT) ? inside : `${owner.id}/${inside}`;
}

/** Rewrites every `//#region <path>` comment with {@link regionName}. */
export function rewriteRegions(code: string): string {
  return code.replace(
    /^\/\/#region (.+)$/gm,
    (_, region: string) => `//#region ${regionName(region)}`,
  );
}

/** True for a module of rolldown's runtime (helpers it injects into a chunk). */
const isRuntime = (moduleId: string): boolean => /^\0?rolldown[:/]runtime/.test(moduleId);

const isLicenseFile = (name: string): boolean =>
  /licen[cs]e|copying/i.test(name) || /^notice/i.test(name);

function normalizeText(text: string): string {
  return text
    .replace(/^\uFEFF/, '')
    .replace(/\r\n?/g, '\n')
    .split('\n')
    .map((line) => line.replace(/\s+$/, ''))
    .join('\n')
    .replace(/^\n+/, '')
    .replace(/\n+$/, '');
}

async function readPackage(dir: string): Promise<Omit<BundledPackage, 'scripts'>> {
  const pkg = JSON.parse(await readFile(path.join(dir, 'package.json'), 'utf8')) as {
    name?: unknown;
    version?: unknown;
    license?: unknown;
    homepage?: unknown;
  };
  const files = (await readdir(dir, { withFileTypes: true }))
    .filter((e) => e.isFile() && isLicenseFile(e.name))
    .map((e) => e.name)
    .sort(compare);
  const texts = [];
  for (const file of files) {
    texts.push({ file, text: normalizeText(await readFile(path.join(dir, file), 'utf8')) });
  }
  return {
    name: String(pkg.name),
    version: String(pkg.version),
    license: typeof pkg.license === 'string' ? pkg.license : 'UNKNOWN',
    homepage: typeof pkg.homepage === 'string' ? pkg.homepage : null,
    texts,
  };
}

/** Bundles every entry and renders the notices (nothing is written). */
export async function build(): Promise<BuildResult> {
  const files = new Map<string, string>();
  const packages = new Map<string, BundledPackage>();
  for (const [script, entry] of Object.entries(ENTRIES)) {
    const bundle = await rolldown({
      input: path.join(PACKAGE_ROOT, entry),
      cwd: PACKAGE_ROOT,
      platform: 'node',
      logLevel: 'warn',
      onLog(level, log) {
        throw new Error(`rolldown ${level} while bundling ${entry}: ${log.message}`);
      },
    });
    try {
      const { output } = await bundle.generate({
        format: 'esm',
        codeSplitting: false,
        banner: banner(script, entry),
        comments: { legal: true, annotation: false, jsdoc: false },
      });
      const [chunk, ...rest] = output;
      if (chunk?.type !== 'chunk' || rest.length > 0) {
        throw new Error(`${entry}: expected exactly one chunk`);
      }
      const external = chunk.imports.filter((i) => !i.startsWith('node:'));
      if (external.length > 0 || chunk.dynamicImports.length > 0) {
        throw new Error(
          `${entry}: the bundle imports ${[...external, ...chunk.dynamicImports].join(', ')}`,
        );
      }
      files.set(`${PLUGIN_DIR}/scripts/${script}`, rewriteRegions(chunk.code));
      const dirs = new Set<string>();
      for (const id of chunk.moduleIds) {
        if (isRuntime(id)) dirs.add(path.join(PACKAGE_ROOT, 'node_modules', 'rolldown'));
        const dir = packageDirOf(id);
        if (dir !== null) dirs.add(dir);
      }
      for (const dir of dirs) {
        const info = await readPackage(dir);
        const key = `${info.name}@${info.version}`;
        const known = packages.get(key) ?? { ...info, scripts: [] };
        known.scripts.push(script);
        packages.set(key, known);
      }
    } finally {
      await bundle.close();
    }
  }
  const sorted = [...packages.values()].sort(
    (a, b) => compare(a.name, b.name) || compare(a.version, b.version),
  );
  files.set(`${PLUGIN_DIR}/${NOTICES_FILE}`, renderNotices(sorted));
  return { files, packages: sorted };
}

/** The plugin's THIRD-PARTY-NOTICES.md. */
export function renderNotices(packages: readonly BundledPackage[]): string {
  const lines = [
    '# Third-party notices: plugin analyzr-integrate',
    '',
    'The scripts in `scripts/` are bundled from `tools/integrate` of analyzr (MIT, `LICENSE` at',
    'the repository root) together with the third-party packages below, at exactly these versions.',
    'Generated by `pnpm --filter @analyzr/integrate generate`; do not edit (a test compares it).',
    '',
    '| Package | Version | License | Bundled into |',
    '|---|---|---|---|',
    ...packages.map(
      (p) => `| ${p.name} | ${p.version} | ${p.license} | ${p.scripts.sort(compare).join(', ')} |`,
    ),
  ];
  for (const p of packages) {
    lines.push('', `## ${p.name} ${p.version} (${p.license})`, '');
    if (p.homepage !== null) lines.push(p.homepage, '');
    if (p.texts.length === 0) lines.push('The package ships no license file.');
    for (const t of p.texts) lines.push(`\`${t.file}\`:`, '', '```text', t.text, '```', '');
    while (lines.at(-1) === '') lines.pop();
  }
  return `${lines.join('\n')}\n`;
}
